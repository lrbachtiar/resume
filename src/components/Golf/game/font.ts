export const GLYPH_H = 6
const ADVANCE = 5

export const textWidth = (text: string) => Math.max(0, text.length * ADVANCE - 1)

export function drawText(c: CanvasRenderingContext2D, text: string, x: number, y: number, color: string) {
  c.fillStyle = color
  ;[...text.toUpperCase()].forEach((ch, i) =>
    (GLYPHS[ch] ?? GLYPHS[' ']).forEach((row, ry) =>
      [...row].forEach((bit, rx) => bit === '#' && c.fillRect(x + i * ADVANCE + rx, y + ry, 1, 1)),
    ),
  )
}
